import { endpoints, type Endpoint } from "../shared/endpoints";

function operation(endpoint: Endpoint) {
  const parameters = (endpoint.parameters ?? []).map((param) => ({
    name: param.name,
    in: param.in,
    description: param.description,
    required: param.required ?? false,
    schema: { type: "string", ...(param.example ? { example: param.example } : {}) },
  }));
  return {
    tags: [endpoint.group],
    summary: endpoint.summary,
    description: endpoint.description,
    operationId: (endpoint.method + "_" + endpoint.path).replace(/[^a-zA-Z0-9]+/g, "_"),
    ...(parameters.length ? { parameters } : {}),
    ...(endpoint.method !== "GET" ? {
      requestBody: {
        required: false,
        content: {
          "application/json": { schema: {} },
          "text/plain": { schema: { type: "string" } },
          "application/x-www-form-urlencoded": { schema: { type: "object", additionalProperties: { type: "string" } } },
          "multipart/form-data": { schema: { type: "object", additionalProperties: true } },
        },
      },
    } : {}),
    responses: {
      "200": {
        description: "Successful HTTP test response",
        content: {
          "application/json": { schema: {} },
          "text/plain": { schema: { type: "string" } },
          "application/octet-stream": { schema: { type: "string", format: "binary" } },
        },
      },
      default: { description: "HTTP response generated by the requested test" },
    },
  };
}

export function openApi(origin: string) {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const endpoint of endpoints) {
    const path = endpoint.path;
    paths[path] ??= {};
    const methods = endpoint.method === "ANY" ? ["get", "post", "put", "patch", "delete"] : [endpoint.method.toLowerCase()];
    for (const method of methods) paths[path][method] = operation(endpoint);
  }
  return {
    openapi: "3.1.0",
    info: { title: "HTTPBin Workers", version: "0.1.0", description: "HTTP request and response inspection on Cloudflare Workers. Some wire-level behavior is controlled by the Workers runtime." },
    servers: [{ url: origin }],
    tags: [...new Set(endpoints.map((entry) => entry.group))].map((name) => ({ name })),
    paths,
  };
}

export function swagger(origin: string) {
  const spec = openApi(origin);
  const paths: Record<string, Record<string, unknown>> = {};
  for (const [path, methods] of Object.entries(spec.paths)) {
    paths[path] = {};
    for (const [method, details] of Object.entries(methods)) {
      const entry = details as ReturnType<typeof operation>;
      paths[path][method] = {
        tags: entry.tags,
        summary: entry.summary,
        description: entry.description,
        operationId: entry.operationId,
        ...( "parameters" in entry ? { parameters: entry.parameters?.map((parameter) => ({ name: parameter.name, in: parameter.in, description: parameter.description, required: parameter.required, type: "string" })) } : {}),
        produces: ["application/json", "text/plain", "application/octet-stream"],
        responses: { "200": { description: "Successful HTTP test response" }, default: { description: "HTTP response generated by the test" } },
      };
    }
  }
  const url = new URL(origin);
  return { swagger: "2.0", info: spec.info, host: url.host, schemes: [url.protocol.replace(":", "")], basePath: "/", tags: spec.tags, paths };
}
